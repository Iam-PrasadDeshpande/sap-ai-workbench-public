"""Experiment F: downloadable learning report. Sanitized; built from session results only; nothing is stored."""
from __future__ import annotations

import csv
import io
import json
from datetime import datetime, timezone

from .contract import EDITION, EVIDENCE_TEXT, LIMITS, VERSION
from .safety import csv_cell, report_text, safe_filename
from .synthetic import ratio_text

NOTICE = ('Generated by the SAP AI Evaluation Workbench public edition. It is a learning aid, not SAP documentation, '
          'not an assessment of your systems and not an approval of anything. Results marked synthetic or documentation '
          'do not prove behaviour in any SAP system.')


# A public report is educational output. Its state is a constant of this module: no parameter, session value or
# field of a report dict can change what is exported (there is no reviewer or approver in the public edition).
PUBLICATION_STATE = 'DRAFT_REVIEW_REQUIRED'


def build(scenario: str, knowledge: dict | None, comparison: dict | None, lab: dict | None, ledger: list,
          improvement: dict, claims: list | None = None, clock=None) -> dict:
    now = (clock or (lambda: datetime.now(timezone.utc)))().isoformat(timespec='seconds')
    return {'edition': EDITION, 'version': VERSION, 'generated_at': now, 'scenario': scenario[:200],
            'publication_state': PUBLICATION_STATE,
            'knowledge': knowledge, 'comparison': comparison, 'lab': lab, 'ledger': ledger, 'improvement': improvement,
            'claims': claims or [], 'notice': NOTICE}


def to_markdown(r: dict) -> str:
    e = report_text
    o = [f"# SAP AI learning report\n\n> {e(r['notice'], 600)}\n",
         f"- Publication state: {PUBLICATION_STATE} (educational draft; not reviewed or approved by anyone)\n"
         f"- Edition: {e(r['edition'])} {e(r['version'])}\n- Generated: {e(r['generated_at'])}\n"
         f"- Scenario: {e(r['scenario'] or 'not stated')}\n"]
    k = r.get('knowledge')
    if k:
        o.append('## Knowledge lookup (SAP public developer service)\n'
                 f"- Question: {e(k['question'])}\n- Retrieved: {e(k['retrieved_at'])}\n"
                 f"- Evidence class: {e(EVIDENCE_TEXT[k['evidence_class']][0])}\n")
        for s in k.get('sources', []):
            o.append(f"- {e(s['title'] or s['slug'])} - {e(s['url'])} (relevance: {e(s['relevance'])}; {e(s['reason'])})")
        o.append('\n### What was and was not shown')
        for ly in k.get('layers', []):
            o.append(f"- {e(ly['layer'])}: {e(ly['status'])} - {e(ly['detail'])}")
        o.append('')
    c = r.get('comparison')
    if c:
        o.append(f"## Architecture comparison: {e(c['title'])}\n- Leaning: {e(c['lean_name'] or c['lean'])} - {e(c['why'])}")
        for x in c.get('reasons', []):
            o.append(f"  - {e(x['priority'])} -> {e(x['option'])}: {e(x['because'])}")
        o.append(f"- Caveat: {e(c['caveat'])}\n")
    lab = r.get('lab')
    if lab:
        o.append('## Synthetic billing lab (FABRICATED DATA)\n'
                 f"- Reference: {e(lab['reference'])}\n- Flagged: {len(lab['flagged'])}; reference size: {len(lab['expected'])}\n"
                 f"- Precision: {e(ratio_text(tuple(lab['precision'])))}; recall: {e(ratio_text(tuple(lab['recall'])))}\n"
                 f"- Result: {e(lab['explanation'])}\n- Proves: {e(lab['proves'])}\n")
    if r.get('ledger'):
        o.append('## Evidence ledger')
        for en in r['ledger']:
            o.append(f"- [{e(en['evidence_class'])}] {e(en['title'])}: {e(en['summary'])} (limits: {e(en['limitations'])})")
        o.append('')
    for cl in r.get('claims', []):
        o.append(f"- Claim: {e(cl['claim'])} - {e(cl['status'])}: {e(cl['explanation'])}")
    imp = r['improvement']
    o.append('\n## Improvement analysis')
    for key, title in (('observed_limitations', 'Observed limitations'), ('hypotheses', 'Hypotheses (not findings)'),
                       ('testable_improvements', 'Testable improvements')):
        o.append(f'### {title}')
        o.extend(f"- {e(i['text'])} ({e(i['basis'])})" for i in imp.get(key, []))
        if not imp.get(key):
            o.append('- none')
    o.append('### Required next evidence')
    o.extend(f'- {e(t)}' for t in imp.get('required_next_evidence', []))
    o.append('### Next hands-on activity')
    o.extend(f'- {e(t)}' for t in imp.get('next_hands_on_activity', []))
    text = '\n'.join(o) + '\n'
    return text[: LIMITS['report_max_bytes']]


def to_json(r: dict) -> str:
    r = {**r, 'publication_state': PUBLICATION_STATE}          # forged or missing values are overwritten, never exported
    return json.dumps(r, indent=2, ensure_ascii=False, sort_keys=True)[: LIMITS['report_max_bytes']]


def lab_csv(lab: dict, cases: list) -> str:
    """The lab result as CSV with spreadsheet formula injection neutralized in every cell."""
    flagged, expected = set(lab['flagged']), set(lab['expected'])
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator='\n')
    w.writerow(['case_id', 'category', 'status', 'amount_cents', 'flagged_by_your_criteria', 'in_reference', 'outcome'])
    for c in cases:
        f, x = c['id'] in flagged, c['id'] in expected
        outcome = 'true_positive' if f and x else 'false_positive' if f else 'false_negative' if x else 'true_negative'
        w.writerow([csv_cell(c['id']), csv_cell(c['category']), csv_cell(c['status']), c['amount_cents'],
                    'yes' if f else 'no', 'yes' if x else 'no', outcome])
    return buf.getvalue()


def filename(kind: str, suffix: str) -> str:
    return safe_filename(f'sap-ai-learning-{kind}', suffix)
